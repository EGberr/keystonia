const DICTS: Record<Lang, Record<TKey, string>> = { en: EN, fr: FR };
const STORAGE_KEY = "keystonia-lang";

type Ctx = {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (k: TKey, vars?: Record<string, string>) => string;
  pick: (obj: object, field: string) => string;
};

// Language preference as an external store: the server (and hydration) render English, then each component
// switches to the stored/browser language — no hydration mismatch, even in late-hydrating Suspense boundaries.
const listeners = new Set<() => void>();
let current: Lang | null = null;

function readLang(): Lang {
  if (current) return current;
  let l: Lang = "en";
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved === "en" || saved === "fr") l = saved;
    else if (navigator.language?.toLowerCase().startsWith("fr")) l = "fr";
  } catch {
    /* storage unavailable */
  }
  current = l;
  return l;
}

function subscribe(cb: () => void) {
  listeners.add(cb);
  return () => listeners.delete(cb);
}

function setLang(l: Lang) {
  current = l;
  try {
    localStorage.setItem(STORAGE_KEY, l);
  } catch {
    /* ignore */
  }
  listeners.forEach((cb) => cb());
}

export function useLang(): Ctx {
  const lang = useSyncExternalStore(subscribe, readLang, () => "en" as Lang);
  return useMemo<Ctx>(
    () => ({
      lang,
      setLang,
      t: (k, vars) => {
        let s: string = DICTS[lang][k] ?? EN[k];
        if (vars) for (const [name, v] of Object.entries(vars)) s = s.replace(`{${name}}`, v);
        return s;
      },
      pick: (obj, field) => {
        const o = obj as Record<string, unknown>;
        return String((lang === "fr" ? o[`${field}_fr`] : undefined) ?? o[field] ?? "");
      },
    }),
    [lang],
  );
}

export function LangProvider({ children }: { children: ReactNode }) {
  const { lang } = useLang();
  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);
  return <>{children}</>;
}
