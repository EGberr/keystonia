// Exports contract ABIs from Foundry artifacts to web/src/lib/abi.ts (typed with `as const` for viem).
import { readFileSync, writeFileSync } from "node:fs";

const names = ["KEUR", "IdentityRegistry", "AssetRegistry", "AssetToken", "Offering", "Marketplace", "AssetGovernor"];
let out = "// Generated by scripts/export-abis.mjs from contracts/out. Do not edit.\n\n";
for (const n of names) {
  const { abi } = JSON.parse(readFileSync(new URL(`../contracts/out/${n}.sol/${n}.json`, import.meta.url)));
  out += `export const ${n}Abi = ${JSON.stringify(abi)} as const;\n\n`;
}
writeFileSync(new URL("../web/src/lib/abi.ts", import.meta.url), out);
console.log(`exported ${names.length} ABIs`);
